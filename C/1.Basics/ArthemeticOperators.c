#include<stdio.h>
int main(){
    // Addition Operation
    int a = 0;
    int Addresult = 1;
    Addresult = a + 3;
    printf("The Addition Operation = %d\n", Addresult);

    // Subtraction Operation
    int b = 0;
    int Subresult = 1;
    Subresult = b - 10;
    printf("The Subtration Operation = %d\n", Subresult);

    // Multiplication Operation
    int c = 0;
    int Mulresult = 1;
    Mulresult = c * 10;
    printf("The Multiplication Operation = %d\n", Mulresult);

    // Division Operation
    int d = 0;
    int Divresult = 1;
    Divresult = d / 10;
    printf("The Division Operation = %d\n", Divresult);

    // Modulo Division- Division with Remainder Operation
    int e = 0;
    int Moduloresult = 1;
    Moduloresult = e % 10;
    printf("The Multiplication Operation = %d\n", Moduloresult);
}