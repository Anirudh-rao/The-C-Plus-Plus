#include<iostream>
using namespace  std;

int main()
{
    //Creating a variable to store  integer
    int var = 10;
    cout<<"The Integer Variable :"<<var;

    //Character data type
    char c = 'A';
    cout<<"\nThe Character variable :"<<c;

    // Creating a boolean variable
    bool isTrue = true;
    cout<<"\nThe Boolean variable :"<<isTrue;

    //Floating variable
    float f = 36.5f;
    cout<<"\nThe Floating variable :"<<f;

    //Double Variable
    double pi = 3.1415926535;
    cout<<"\nThe Double variable :"<<pi;

    return 0;

}